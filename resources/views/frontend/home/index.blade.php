    <script>
        (function() {
            // Finds the first seminar-card on the page (if multiple, you can adapt)
            const card = document.querySelector('.seminar-card');
            if (!card) return;

            // read datetime string from data- attribute (ISO format recommended)
            const dtStr = card.dataset.datetime;
            const targetDate = dtStr ? new Date(dtStr) : null;
            if (!targetDate || isNaN(targetDate)) return;

            // elements
            const daysEl = card.querySelector('.days');
            const hoursEl = card.querySelector('.hours');
            const minutesEl = card.querySelector('.minutes');
            const secondsEl = card.querySelector('.seconds');

            function pad(n) {
                return String(n).padStart(2, '0');
            }

            function updateCountdown() {
                const now = new Date();
                const diff = targetDate - now;
                if (diff <= 0) {
                    daysEl.textContent = '00';
                    hoursEl.textContent = '00';
                    minutesEl.textContent = '00';
                    secondsEl.textContent = '00';
                    clearInterval(timer);
                    return;
                }
                const secs = Math.floor(diff / 1000);
                const days = Math.floor(secs / 86400);
                const hours = Math.floor((secs % 86400) / 3600);
                const minutes = Math.floor((secs % 3600) / 60);
                const seconds = secs % 60;

                if (daysEl) daysEl.textContent = pad(days);
                if (hoursEl) hoursEl.textContent = pad(hours);
                if (minutesEl) minutesEl.textContent = pad(minutes);
                if (secondsEl) secondsEl.textContent = pad(seconds);
            }

            // initial update + interval
            updateCountdown();
            const timer = setInterval(updateCountdown, 1000);

            // optional: stop countdown if element removed
            const observer = new MutationObserver(() => {
                if (!document.body.contains(card)) {
                    clearInterval(timer);
                    observer.disconnect();
                }
            });
            observer.observe(document.body, {
                childList: true
                , subtree: true
            });
        })();

    </script>
