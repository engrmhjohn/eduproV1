        (function() {
            function makeIframe(src) {
                var iframe = document.createElement('iframe');
                iframe.setAttribute('src', src);
                iframe.setAttribute('allow', 'accelerometer; autoplay; encrypted-media; gyroscope; picture-in-picture; web-share');
                iframe.setAttribute('allowfullscreen', '');
                iframe.style.width = '100%';
                iframe.style.height = '100%';
                iframe.style.border = '0';
                iframe.style.display = 'block';
                iframe.style.borderRadius = '12px';
                return iframe;
            }

            document.querySelectorAll('.video-thumb-wrap').forEach(function(wrap) {
                // keyboard accessibility
                wrap.setAttribute('tabindex', '0');

                function activate() {
                    var embed = wrap.dataset.videoEmbed;
                    if (!embed) return;
                    // prevent re-inject if already playing
                    if (wrap.classList.contains('playing')) return;

                    // clear existing content (thumb, overlay, button) and inject iframe
                    wrap.classList.add('playing');

                    // create container for iframe sized to fill wrapper
                    var iframe = makeIframe(embed);

                    // insert iframe as first child so it fills
                    wrap.innerHTML = '';
                    wrap.appendChild(iframe);
                }

                wrap.addEventListener('click', function(e) {
                    // ignore clicks that come from interactive inner controls? just activate
                    activate();
                });

                wrap.addEventListener('keydown', function(e) {
                    if (e.key === 'Enter' || e.key === ' ') {
                        e.preventDefault();
                        activate();
                    }
                });
            });
        })();

